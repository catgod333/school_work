number = input(" Enter your number: ")
number = float(number)
if number > 100:
    print(number,"is greater than 100")
if number < 100:
    print(number,"is less than 100")
if number >= 100:
    print(number,"is greater than or equal to 100")
if number <= 100:
    print(number,"is less than or equal to 100")
if number == 100:
    print(number,"is equal to 100")
if number != 100:
    print(number,"is not equal to 100")
